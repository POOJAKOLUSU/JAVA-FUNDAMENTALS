public class EscapeCharacters {
    public static void main(String[] args) {
        
        // 1. Newline (\n) - moves output to the next line
        System.out.println("Line 1\nLine 2");
        
        // 2. Tab (\t) - adds vertical alignment / spacing
        System.out.println("Name:\tAlice");
        System.out.println("Age:\t25");
        
        // 3. Double Quotes (\") - prints a quotation mark inside a string
        System.out.println("She said, \"Java is fun!\"");
        
        // 4. Single Quotes (\') - used inside text or char literals
        System.out.println("It\'s a sunny day.");
        
        // 5. Backslash (\\) - prints a literal backslash (useful for paths)
        System.out.println("File path: C:\\Users\\Java\\Code.java");
    }
}
